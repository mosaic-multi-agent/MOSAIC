package opencodev2

// pluginTemplate is the generated interceptor plugin module. The tokens
// __PRE__, __POST__ and __COMPLETION__ are replaced by each bridge's JSON
// literal ({"executable": ..., "args": [...]}). The module is written as
// plain JavaScript so it loads as a .ts file without a type-stripping step.
//
// V2 reports a subagent launch from execute.after about 15 ms after
// execute.before, and delivers the child's final text later as a synthetic
// wake-up on the event stream. The plugin therefore forwards three things:
// the dispatch before it runs (which may be rewritten or rejected), the launch
// acknowledgement, and the child's first finished wake-up, joined to its
// dispatch through the child session id the launch returned.
const pluginTemplate = `// Code generated by mosaic-agent-test. DO NOT EDIT.
//
// Bridges OpenCode V2's tool hooks and event stream to the mosaic-agent-test
// interceptor. It intercepts the subagent tool only.

import { spawn } from "node:child_process";

const DISPATCH_TOOL = "subagent";
const DENY_DEFAULT_REASON = "This operation cannot proceed.";
const INTERCEPTOR_TIMEOUT_MS = 60000;
const RESUBSCRIBE_DELAY_MS = 250;

const BRIDGES = {
  pre: __PRE__,
  post: __POST__,
  completion: __COMPLETION__,
};

function isObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

// runInterceptor starts the interceptor for one forward, writes the payload to
// its stdin and resolves with its JSON object reply, or null when there is no
// usable reply (spawn failure, non-zero exit, empty or non-JSON output). Its
// output is captured and never reaches the host.
function runInterceptor(phase, payload) {
  return new Promise((resolve) => {
    let settled = false;
    const finish = (value) => {
      if (!settled) {
        settled = true;
        resolve(value);
      }
    };
    try {
      const bridge = BRIDGES[phase];
      const child = spawn(bridge.executable, bridge.args, { stdio: ["pipe", "pipe", "pipe"], windowsHide: true });
      let stdout = "";
      const timer = setTimeout(() => {
        try {
          child.kill();
        } catch {}
        finish(null);
      }, INTERCEPTOR_TIMEOUT_MS);
      child.stdout.setEncoding("utf8");
      child.stdout.on("data", (chunk) => {
        stdout += chunk;
      });
      child.stderr.on("data", () => {});
      child.stdin.on("error", () => {});
      child.on("error", () => {
        clearTimeout(timer);
        finish(null);
      });
      child.on("close", (code) => {
        clearTimeout(timer);
        if (code !== 0 || !stdout.trim()) {
          finish(null);
          return;
        }
        try {
          const reply = JSON.parse(stdout);
          finish(isObject(reply) ? reply : null);
        } catch {
          finish(null);
        }
      });
      child.stdin.end(JSON.stringify(payload));
    } catch {
      finish(null);
    }
  });
}

function isReCall(input) {
  return isObject(input) && typeof input.sessionID === "string" && input.sessionID !== "";
}

function launchedChild(event) {
  const result = event.result;
  if (!isObject(result)) return "";
  if (isObject(result.metadata) && typeof result.metadata.sessionID === "string" && result.metadata.sessionID) {
    return result.metadata.sessionID;
  }
  if (isObject(result.output) && typeof result.output.sessionID === "string" && result.output.sessionID) {
    return result.output.sessionID;
  }
  return "";
}

function rejection(reason) {
  const error = new Error(reason);
  error._tag = "Tool.Error";
  return error;
}

export default {
  id: "mosaic-interceptor",
  setup(ctx) {
    let stopped = false;
    const abort = new AbortController();
    // Sessions known to be children of a subject session: their dispatches are
    // not forwarded.
    const childSessions = new Set();
    // Dispatches waiting for their child's first finished wake-up, keyed by
    // the child session id.
    const pending = new Map();

    const isDispatchFromSubject = (event) =>
      !stopped &&
      isObject(event) &&
      event.tool === DISPATCH_TOOL &&
      !isReCall(event.input) &&
      !childSessions.has(event.sessionID);

    const wireFields = (event) => ({
      tool: event.tool,
      sessionID: event.sessionID,
      agent: event.agent,
      messageID: event.messageID,
      id: event.id,
      input: event.input,
    });

    const onBefore = async (event) => {
      let reply = null;
      try {
        if (!isDispatchFromSubject(event)) return;
        reply = await runInterceptor("pre", { hook_event_name: "execute.before", ...wireFields(event) });
      } catch {
        return;
      }
      if (!reply) return;
      if (reply.decision === "deny") {
        throw rejection(typeof reply.reason === "string" && reply.reason ? reply.reason : DENY_DEFAULT_REASON);
      }
      if (reply.decision === "allow" && isObject(reply.updatedInput)) {
        try {
          if (!isObject(event.input)) event.input = {};
          Object.assign(event.input, reply.updatedInput);
        } catch {}
      }
    };

    const onAfter = async (event) => {
      try {
        if (stopped || !isObject(event) || event.tool !== DISPATCH_TOOL) return;
        const forwarded = isDispatchFromSubject(event);
        const child = launchedChild(event);
        if (child) childSessions.add(child);
        if (!forwarded) return;
        if (event.status === "completed" && child) {
          const agent = isObject(event.input) && typeof event.input.agent === "string" ? event.input.agent : "";
          pending.set(child, { id: event.id, agent });
        }
        const payload = { hook_event_name: "execute.after", ...wireFields(event), status: event.status };
        if (event.result !== undefined) payload.result = event.result;
        if (event.error !== undefined) payload.error = event.error;
        await runInterceptor("post", payload);
      } catch {}
    };

    const onEvent = async (event) => {
      if (stopped || !isObject(event) || !isObject(event.data)) return;
      const data = event.data;
      if (event.type === "session.created") {
        if (typeof data.parentID === "string" && data.parentID && typeof data.sessionID === "string") {
          childSessions.add(data.sessionID);
        }
        return;
      }
      if (event.type !== "session.inbox.enqueued") return;
      const item = data.item;
      if (!isObject(item) || item.type !== "synthetic" || !isObject(item.payload)) return;
      const meta = item.payload.metadata;
      if (!isObject(meta) || meta.source !== "subagent" || meta.state === "running") return;
      const record = pending.get(meta.childID);
      if (!record) return;
      pending.delete(meta.childID);
      await runInterceptor("completion", {
        hook_event_name: "subagent.completed",
        sessionID: data.sessionID,
        id: record.id,
        agent: record.agent,
        childSessionID: meta.childID,
        state: meta.state,
        text: item.payload.text,
      });
    };

    const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

    const subscribeLoop = async () => {
      while (!stopped) {
        try {
          const events = ctx.event.subscribe({ signal: abort.signal });
          for await (const event of events) {
            if (stopped) return;
            try {
              await onEvent(event);
            } catch {}
          }
        } catch {}
        if (stopped) return;
        await sleep(RESUBSCRIBE_DELAY_MS);
      }
    };

    try {
      ctx.tool.hook("execute.before", onBefore);
    } catch {}
    try {
      ctx.tool.hook("execute.after", onAfter);
    } catch {}
    try {
      if (ctx.event && typeof ctx.event.subscribe === "function") subscribeLoop().catch(() => {});
    } catch {}

    return () => {
      stopped = true;
      try {
        abort.abort();
      } catch {}
    };
  },
};
`
